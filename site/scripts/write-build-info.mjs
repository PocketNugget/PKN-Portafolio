import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function git(cmd) {
  try {
    return execSync(cmd, { cwd: join(root, ".."), encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

const commit = git("git rev-parse --short HEAD");
const built = new Date().toISOString();

const source = `// Generated by scripts/write-build-info.mjs. Do not edit by hand.
export const buildInfo = {
  commit: ${JSON.stringify(commit)},
  built: ${JSON.stringify(built)},
} as const;
`;

writeFileSync(join(root, "src/build-info.ts"), source);
